import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compare, packageKey, parseNoticeTexts, sha256, validateInventory, webUrl } from './licenses/catalog.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (name) => fs.readFile(path.join(root, name), 'utf8');
const json = async (name) => JSON.parse(await read(name));
const check = process.argv.includes('--check');
const lock = await json('package-lock.json');
let inventory = await json('licenses/third-party/common/npm-inventory.json');
const texts = parseNoticeTexts(await read('licenses/third-party/common/npm-notices.txt'));
if (process.argv.includes('--refresh')) {
  if (check) throw new Error('--refresh and --check are mutually exclusive');
  const { refreshInventory } = await import('./licenses/refresh.mjs');
  inventory = await refreshInventory(root, lock, inventory, texts);
}
validateInventory(lock, inventory, texts);
const snapshots = await json('licenses/third-party/snapshots.json');
for (const file of snapshots.files) {
  if (sha256(await read(`licenses/third-party/${file.path}`)) !== file.sha256) {
    throw new Error(`Reviewed snapshot changed: ${file.path}. Review and update snapshots.json.`);
  }
}
for (const [name, version] of Object.entries(snapshots.versions)) {
  const lookup = name === 'sharp-libvips-posix' ? '@img/sharp-libvips-darwin-arm64' : name === 'sharp-win32' ? '@img/sharp-win32-x64' : name;
  if (lock.packages[`node_modules/${lookup}`]?.version !== version) throw new Error(`Native snapshot version is stale: ${name}`);
}

const documents = new Map();
function document(title, text) {
  const id = sha256(text);
  documents.set(id, text);
  return { title, id };
}
const fileDocument = async (name, title = path.basename(name)) => document(title, await read(name));
const entries = [];
for (const pkg of inventory.packages) {
  entries.push({
    id: sha256(`npm:${packageKey(pkg)}`).slice(0, 24), name: pkg.name, version: pkg.version, license: pkg.license,
    repository: webUrl(pkg.repository), website: webUrl(pkg.homepage) ?? `https://www.npmjs.com/package/${pkg.name}/v/${pkg.version}`,
    documents: pkg.licenseFiles.map((file) => document(file.source, texts.get(file.sha256))),
  });
}
const extras = await json('licenses/third-party/catalog-supplements.json');
for (const entry of extras) {
  const { files, ...metadata } = entry;
  entries.push({ ...metadata, documents: await Promise.all(files.map((name) => fileDocument(name))) });
}
// Expose each reviewed mobile source by name; preserve its complete notice collection.
const mobile = await json('licenses/third-party/common/mobile-sources.json');
const mobileNotice = await fileDocument('licenses/third-party/common/mobile-native.txt');
for (const source of mobile.sources) {
  const version = source.component.split(' ').at(-1);
  const repository = source.url.match(/^https:\/\/codeload.github.com\/([^/]+\/[^/]+)\//)?.[1];
  entries.push({ id: sha256(`native:${source.component}`).slice(0, 24),
    name: source.component.slice(0, -(version.length + 1)), version,
    license: '', repository: repository ? `https://github.com/${repository}` : undefined,
    documents: [mobileNotice] });
}
// Each Rust crate in the existing librsvg collection is independently searchable.
const rust = await read('licenses/third-party/desktop/librsvg-rust.txt');
const rustParts = [...rust.matchAll(/^librsvg Rust dependency (\S+) (\S+)\n/gm)];
const crates = new Map();
for (let i = 0; i < rustParts.length; i++) {
  const match = rustParts[i];
  const [, name, version] = match;
  const key = `${name}@${version}`;
  const entry = crates.get(key) ?? { id: sha256(`rust:${key}`).slice(0, 24), name, version, license: '',
    website: `https://crates.io/crates/${name}/${version}`, documents: [] };
  const body = rust.slice(match.index + match[0].length, rustParts[i + 1]?.index ?? rust.length);
  const title = body.slice(0, body.indexOf('\n'));
  const doc = document(title, body.slice(title.length + 2));
  if (!entry.documents.some((item) => item.id === doc.id)) entry.documents.push(doc);
  crates.set(key, entry);
}
entries.push(...crates.values());
entries.sort((a, b) => compare(a.name.replace(/^@/, '').toLowerCase(), b.name.replace(/^@/, '').toLowerCase()) || compare(a.id, b.id));
if (new Set(entries.map((entry) => entry.id)).size !== entries.length) throw new Error('Duplicate catalog IDs');

const outputs = new Map();
outputs.set('src/generated/licenses/catalog.json', JSON.stringify(entries) + '\n');
for (const [id, text] of documents) outputs.set(`assets/licenses/${id}.txt`, text);
const assetLines = [...documents.keys()].sort(compare).map((id) => `  '${id}': () => require('../../../assets/licenses/${id}.txt'),`);
outputs.set('src/generated/licenses/assets.ts', '// Generated by scripts/generate-licenses.mjs. Do not edit.\n' +
  '/* eslint-disable @typescript-eslint/no-require-imports */\n' +
  'export const noticeAssets: Readonly<Record<string, () => number>> = {\n' + assetLines.join('\n') + '\n};\n');
// Hash the inputs so CI catches changes even when their current display happens to be identical.
const inputs = ['package-lock.json', 'LICENSE', 'licenses/zxing-cpp/LICENSE', 'licenses/zxing-cpp/NOTICE',
  'licenses/third-party/common/npm-inventory.json', 'licenses/third-party/common/npm-notices.txt',
  'licenses/third-party/catalog-supplements.json', 'licenses/third-party/snapshots.json',
  ...snapshots.files.map((file) => `licenses/third-party/${file.path}`)];
const hashes = Object.fromEntries(await Promise.all(inputs.sort(compare).map(async (name) => [name, sha256(await read(name))])));
outputs.set('src/generated/licenses/inputs.json', JSON.stringify(hashes, null, 2) + '\n');
const stale = [];
for (const [name, value] of outputs) {
  if (check) {
    if (await read(name).catch(() => null) !== value) stale.push(name);
  } else {
    await fs.mkdir(path.dirname(path.join(root, name)), { recursive: true });
    await fs.writeFile(path.join(root, name), value);
  }
}
for (const name of await fs.readdir(path.join(root, 'assets/licenses')).catch(() => [])) {
  if (!outputs.has(`assets/licenses/${name}`)) {
    if (check) stale.push(`assets/licenses/${name}`);
    else await fs.unlink(path.join(root, 'assets/licenses', name));
  }
}
if (stale.length) throw new Error(`Generated notices are stale (${stale.length} files). Run npm run licenses:generate.`);
console.log(`${check ? 'Verified' : 'Generated'} ${entries.length} projects and ${documents.size} original notice texts.`);
