import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import path from 'node:path';
import { tmpdir } from 'node:os';
import { spawn } from 'node:child_process';
import { build } from 'esbuild';
import electron from 'electron';

test('Electron application hosts keep independent containers, owned IPC and shared signing invalidation', { timeout: 60000 }, async () => {
  const dir = await mkdtemp(path.join(tmpdir(), 'psst-application-windows-'));
  try {
    for (const entry of ['preload', 'napplet-preload']) await build({ entryPoints: [`desktop/${entry}.ts`], bundle: true, platform: 'node', format: 'cjs', external: ['electron'], outfile: path.join(dir, `${entry}.js`) });
    await build({ stdin: { contents: `import ${JSON.stringify(path.resolve('desktop/preload.ts'))};const {contextBridge,ipcRenderer}=require('electron');const events=[];for(const channel of ['napplet:message','application-window:signing-change','application-window:metadata-change','application-window:favorites-change','application-window:action','local-relay:event'])ipcRenderer.on(channel,(_e,...args)=>events.push({channel,args}));contextBridge.exposeInMainWorld('hostTest',{invoke:(...args)=>ipcRenderer.invoke(...args),events:()=>events});`, resolveDir: process.cwd() }, bundle: true, platform: 'node', format: 'cjs', external: ['electron'], outfile: path.join(dir, 'host-preload.js') });
    const entry = `
      import { app, BrowserWindow, webContents, ipcMain, screen } from 'electron';
      import { strict as assert } from 'node:assert';
      import { createServer } from 'node:http';
      process.on('uncaughtException',error=>{console.error(error);app.exit(1);});
      import { ApplicationWindows } from ${JSON.stringify(path.resolve('desktop/application-windows.ts'))};
      import { registerNappletHandlers } from ${JSON.stringify(path.resolve('desktop/napplet-service.ts'))};
      import { IPC } from ${JSON.stringify(path.resolve('desktop/ipc-channels.ts'))};
      import { finalizeEvent, generateSecretKey } from 'nostr-tools';
      import { naddrEncode, neventEncode } from 'nostr-tools/nip19';
      app.setPath('userData', ${JSON.stringify(path.join(dir, 'profile'))});
      const pause=ms=>new Promise(resolve=>setTimeout(resolve,ms));
      app.whenReady().then(async()=>{
        ipcMain.on(IPC.notificationSupported,event=>{event.returnValue=false;});
        const create=(child=false)=>new BrowserWindow({show:false,webPreferences:{sandbox:true,contextIsolation:true,nodeIntegration:false,preload:${JSON.stringify(path.join(dir, 'host-preload.js'))},additionalArguments:['--psstpsst-application-window='+(child?'1':'0')]}});
        const parent=create();await parent.loadURL('data:text/html,<title>Main</title>');
        const cleaned=[];
        const trusted=event=>(event.sender===parent.webContents||manager.owns(event.sender))&&event.senderFrame===event.sender.mainFrame;
        const manager=new ApplicationWindows({create:()=>create(true),parent:()=>parent,url:()=> 'data:text/html,<title>Application</title>',cleanup:id=>cleaned.push(id),trusted});
        manager.register();registerNappletHandlers(trusted,()=>parent);
        const invoke=(owner,channel,...args)=>owner.webContents.executeJavaScript('hostTest.invoke('+[channel,...args].map(x=>JSON.stringify(x)).join(',')+')');
        const events=owner=>owner.webContents.executeJavaScript('hostTest.events()');
        const launch={accountPubkey:'a'.repeat(64),address:'https://example.com'};
        const area=screen.getDisplayMatching(parent.getBounds()).workArea;
        parent.setBounds({x:area.x+40,y:area.y+40,width:600,height:600});
        const parentBounds=parent.getBounds();
        await invoke(parent,IPC.applicationWindowOpen,launch);
        const first=manager.windows()[0];assert(first);assert.equal(await first.webContents.executeJavaScript('psstpsstDesktop.napplet.windows.isHost'),true);
        assert.deepEqual(parent.getBounds(),parentBounds,'opening an application preserves source geometry');
        assert(first.getBounds().x!==parentBounds.x||first.getBounds().y!==parentBounds.y,'new applications must not exactly cover the launching window');
        assert.deepEqual(await invoke(first,IPC.applicationWindowLaunch),launch);
        assert.equal(await invoke(parent,IPC.applicationWindowLaunch),null);
        await invoke(first,IPC.applicationWindowOpen,{...launch,accountPubkey:'b'.repeat(64)});
        const second=manager.windows()[1];assert(second);
        const firstBounds=first.getBounds(),secondBounds=second.getBounds();
        assert(firstBounds.x!==secondBounds.x||firstBounds.y!==secondBounds.y,'nested opens are positioned relative to the application host');
        await invoke(parent,IPC.applicationWindowOpen,launch);
        assert.equal(manager.windows().length,2,'reopening reuses the existing application');
        assert.deepEqual(first.getBounds(),firstBounds,'reusing an application preserves its position');
        const secret=generateSecretKey();
        const manifest=finalizeEvent({kind:35130,created_at:1,tags:[['d','identity-test']],content:''},secret);
        const coordinate='35130:'+manifest.pubkey+':identity-test';
        const canonical={accountPubkey:launch.accountPubkey,address:naddrEncode({kind:35130,pubkey:manifest.pubkey,identifier:'identity-test'})};
        const reference={accountPubkey:launch.accountPubkey,address:neventEncode({id:manifest.id})};
        await invoke(parent,IPC.applicationWindowOpen,reference);
        const provisional=manager.windows().at(-1);
        assert.equal(await invoke(provisional,IPC.applicationWindowResolveIdentity,manifest),true);
        assert((await invoke(parent,IPC.applicationWindowsRunning)).some(item=>item.sourceId===coordinate),'resolved windows register the eventKey');
        await invoke(parent,IPC.applicationWindowOpen,canonical);
        assert.equal(manager.windows().length,3,'the canonical address reuses the event-reference host');
        const newer=finalizeEvent({kind:35130,created_at:2,tags:[['d','identity-test']],content:''},secret);
        const another={accountPubkey:launch.accountPubkey,address:neventEncode({id:newer.id})};
        await invoke(parent,IPC.applicationWindowOpen,another);
        const redundant=manager.windows().at(-1);
        const merged=new Promise(resolve=>redundant.once('closed',resolve));
        void invoke(redundant,IPC.applicationWindowResolveIdentity,newer).catch(()=>false);
        await merged;
        assert.equal(manager.windows().length,3,'reference collisions close the provisional host');
        await invoke(parent,IPC.applicationWindowOpen,another);
        assert.equal(manager.windows().length,3,'known reference aliases reuse the canonical host');
        await assert.rejects(invoke(provisional,IPC.applicationWindowResolveIdentity,{...manifest,id:'f'.repeat(64)}),/invalid-application-identity/);
        provisional.close();await pause(40);
        const publicAddition={origin:'first-host',event:{id:'c'.repeat(64),pubkey:'a'.repeat(64),sig:'d'.repeat(128),kind:1,created_at:100,content:'x'.repeat(2*1024*1024+1024),tags:[]}};
        await first.webContents.executeJavaScript('psstpsstDesktop.localRelayEvents.publish('+JSON.stringify(publicAddition)+')');await pause(40);
        for(const owner of [parent,second])assert((await events(owner)).some(e=>e.channel===IPC.localRelayEvent&&e.args[0].event.content.length===publicAddition.event.content.length));
        assert(!(await events(first)).some(e=>e.channel===IPC.localRelayEvent),'public additions never echo to their origin host');
        await assert.rejects(invoke(first,IPC.localRelayEvent,{...publicAddition,event:{...publicAddition.event,kind:4}}),/invalid-local-relay-event/);
        const bundle=title=>({sourceId:'same-app',storageId:'same-account',network:false,script:'',files:[{path:'/index.html',mime:'text/html',body:Buffer.from('<title>'+title+'</title><p>'+title+'</p>').toString('base64')}]});
        const firstId=await invoke(first,IPC.exploreOpen,bundle('First'));
        const secondId=await invoke(second,IPC.exploreOpen,bundle('Second'));
        const views=()=>webContents.getAllWebContents().filter(w=>w.getURL().includes('.explore.psstpsst.invalid'));
        assert.equal(views().length,2,'opening a second window preserves the first container');
        await assert.rejects(invoke(first,IPC.nappletClose,secondId),/untrusted-container-owner/);
        await assert.rejects(invoke(parent,IPC.nappletSend,firstId,'{}'),/untrusted-container-owner/);
        await invoke(second,IPC.nappletClose,secondId);
        assert.equal(views().length,1);
        const firstView=views()[0];await firstView.reload();await pause(150);
        assert.equal(await Promise.race([firstView.executeJavaScript('navigator.storage.persist()'),pause(2000).then(()=> 'unexpected-storage-prompt')]),true,'persistent storage is granted without a consent sheet');

        assert.equal(await firstView.executeJavaScript('document.title'),'First','closing another host preserves this profile protocol');
        const metadataKey='naddr1metadata-key';
        await invoke(first,IPC.applicationMetadataChange,metadataKey);await pause(40);
        assert((await events(parent)).some(e=>e.channel===IPC.applicationMetadataChange&&e.args[0]===metadataKey));
        assert((await events(second)).some(e=>e.channel===IPC.applicationMetadataChange&&e.args[0]===metadataKey));
        assert(!(await events(first)).some(e=>e.channel===IPC.applicationMetadataChange),'metadata notifications never echo to the sender');
        await assert.rejects(invoke(first,IPC.applicationMetadataChange,''),/invalid-metadata-change/);
        await invoke(first,IPC.applicationFavoritesChange,launch.accountPubkey);await pause(40);
        assert((await events(parent)).some(e=>e.channel===IPC.applicationFavoritesChange&&e.args[0]===launch.accountPubkey));
        assert((await events(second)).some(e=>e.channel===IPC.applicationFavoritesChange&&e.args[0]===launch.accountPubkey));
        assert(!(await events(first)).some(e=>e.channel===IPC.applicationFavoritesChange),'favorite membership notifications never echo to the sender');
        await assert.rejects(invoke(first,IPC.applicationFavoritesChange,'invalid'),/invalid-favorites-change/);
        const change={accountPubkey:launch.accountPubkey,sourceId:'https://example.com',key:'publish:1'};
        await invoke(first,IPC.applicationSigningChange,change);await pause(40);
        assert((await events(parent)).some(e=>e.channel===IPC.applicationSigningChange&&e.args[0].key===change.key));
        assert.equal((await events(first)).filter(e=>e.channel===IPC.applicationSigningChange).length,0,'broadcast never echoes');
        const share={type:'share',accountPubkey:launch.accountPubkey,title:'Example',address:launch.address};
        await invoke(first,IPC.applicationWindowAction,share);await pause(40);
        assert((await events(parent)).some(e=>e.channel===IPC.applicationWindowAction&&e.args[0].title==='Example'));
        await assert.rejects(invoke(first,IPC.applicationWindowAction,{...share,accountPubkey:'b'.repeat(64)}),/invalid-window-action/);
        const discover={type:'discover',accountPubkey:launch.accountPubkey,name:'view:1',auxiliary:false};
        await invoke(first,IPC.applicationWindowAction,discover);await pause(40);
        assert((await events(parent)).some(e=>e.channel===IPC.applicationWindowAction&&e.args[0].type==='discover'&&e.args[0].name==='view:1'));
        for(const invalid of [{...discover,accountPubkey:'b'.repeat(64)},{...discover,name:''},{...discover,auxiliary:'false'}])
          await assert.rejects(invoke(first,IPC.applicationWindowAction,invalid),/invalid-window-action/);
        const publisher={type:'publisher',pubkey:'c'.repeat(64)};
        await invoke(first,IPC.applicationWindowAction,publisher);await pause(40);
        assert((await events(parent)).some(e=>e.channel===IPC.applicationWindowAction&&e.args[0].type==='publisher'&&e.args[0].pubkey===publisher.pubkey));
        await assert.rejects(invoke(first,IPC.applicationWindowAction,{type:'publisher',pubkey:'invalid'}),/invalid-window-action/);
        await assert.rejects(invoke(first,IPC.applicationWindowCloseAll),/untrusted-window-owner/);
        const firstOwner=first.webContents.id;
        await invoke(parent,IPC.applicationWindowCloseAll,launch.accountPubkey);await pause(50);
        assert(first.isDestroyed());assert(!second.isDestroyed());assert(cleaned.includes(firstOwner));assert.equal(views().length,0);
        const server=createServer((_request,response)=>response.end('<title>Website</title>'));
        await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
        const website={sourceId:'website',storageId:'same-account',network:true,script:'',url:'http://127.0.0.1:'+server.address().port};
        const websiteId=await invoke(second,IPC.exploreOpen,website);
        await invoke(second,IPC.nappletClose,websiteId);
        await invoke(second,IPC.nappletClose,websiteId);
        await invoke(second,IPC.exploreOpen,website);
        second.close();await pause(50);assert(second.isDestroyed(),'closing a website host must not unregister a bundle protocol');
        await new Promise(resolve=>server.close(resolve));
        await invoke(parent,IPC.applicationWindowCloseAll);await pause(30);
        const outsider=create();await outsider.loadURL('data:text/html,Outsider');
        await assert.rejects(invoke(outsider,IPC.applicationWindowOpen,launch),/untrusted-application-host/);
        outsider.destroy();parent.destroy();app.exit(0);
      }).catch(error=>{console.error(error);app.exit(1);});
    `;
    await build({ stdin: { contents: entry, loader: 'ts', resolveDir: process.cwd() }, bundle: true, platform: 'node', format: 'cjs', external: ['electron'], outfile: path.join(dir, 'main.js') });
    const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE;
    const child = spawn(electron, [path.join(dir, 'main.js')], { env, stdio: ['ignore', 'pipe', 'pipe'] });
    let output = ''; child.stdout.on('data', chunk => output += chunk); child.stderr.on('data', chunk => output += chunk);
    const timer = setTimeout(() => child.kill('SIGKILL'), 50000);
    const code = await new Promise(resolve => child.once('exit', resolve)); clearTimeout(timer);
    assert.equal(code, 0, output);
  } finally { await rm(dir, { recursive: true, force: true }); }
});
