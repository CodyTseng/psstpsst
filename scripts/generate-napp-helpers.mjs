import { build } from 'esbuild';
import { Buffer } from 'node:buffer';
import { readFile, writeFile } from 'node:fs/promises';

// Keep the pinned vendor files unchanged; derive the same icon-mask CSS as upstream.
const vendor = await build({ entryPoints: [new URL('../src/lib/napp/vendor/ui.ts', import.meta.url).pathname], bundle: true,
  write: false, platform: 'node', format: 'esm' });
const { icons, iconInk } = await import(`data:text/javascript;base64,${Buffer.from(vendor.outputFiles[0].text).toString('base64')}`);
const masks = Object.entries(icons).map(([name, body]) => {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" fill="none" stroke="#000" stroke-width="1.4" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`;
  const url = `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`;
  const ink = iconInk[name];
  return `.ui-icon-${name}{display:inline-block;width:1em;height:1em;background-color:currentColor;-webkit-mask:center/contain no-repeat;mask:center/contain no-repeat;-webkit-mask-image:url("${url}");mask-image:url("${url}");${ink ? `--ink-start:${ink[0]}em;--ink-end:${ink[1]}em;` : ''}}`;
}).join('\n');
const css = await readFile(new URL('../src/lib/napp/vendor/ui.css', import.meta.url), 'utf8');
await writeFile(new URL('../src/lib/napp/ui-styles.generated.ts', import.meta.url),
  '// Generated by scripts/generate-napp-helpers.mjs from the pinned Unlicense UI kit.\n' +
  `export const nappUiStyles = ${JSON.stringify(css + '\n' + masks)};\n`);

const result = await build({
  entryPoints: [new URL('../src/lib/napp/pure-helpers.ts', import.meta.url).pathname],
  bundle: true, write: false, platform: 'browser', format: 'iife', globalName: 'PsstNappHelpers',
  target: 'es2022', minify: true, legalComments: 'inline',
});
await writeFile(new URL('../src/lib/napp/pure-helpers.generated.ts', import.meta.url),
  '// Generated by scripts/generate-napp-helpers.mjs.\n' +
  `export const nappPureHelpers = ${JSON.stringify(result.outputFiles[0].text)};\n`);

// Hermes does not preserve executable source in Function.prototype.toString().
