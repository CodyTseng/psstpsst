import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
let source = readFileSync(require.resolve('@napplet/shim/prelude.global'), 'utf8');
// Keep the injected OUTBOX SDK promise alive across the bounded 16-request
// approval queue, routing and signing budgets.
const publishTimeout = /(function publish\(template, options\) \{[\s\S]*?\}, )REQUEST_TIMEOUT_MS9(\);)/g;
if ([...source.matchAll(publishTimeout)].length !== 1) {
  throw new Error('Pinned OUTBOX publish timeout changed; review the approval budget override.');
}
source = source.replace(publishTimeout, (_match, start, end) => `${start}1020000${end}`);
// Optional capabilities can wait behind sixteen one-minute approval reviews.
const requestTimeouts = /var REQUEST_TIMEOUT_MS\d* = (?:3e4|5e3);/g;
if ([...source.matchAll(requestTimeouts)].length !== 20) {
  throw new Error('Pinned SDK request timeouts changed; review the capability approval budget.');
}
source = source.replace(requestTimeouts, match => match.replace(/(?:3e4|5e3)/, '1020000'));
// These SDK methods do not otherwise release their timeout after settlement.
for (const [map, id, extra] of [
  ['pendingResponses', 'message.id', ''], ['pendingGets', 'id', ''], ['pendingRegistrations2', 'id', ', schema'],
]) {
  const entry = `${map}.set(${id}, { resolve, reject${extra} });`;
  const timer = `setTimeout(() => {\n        if (${map}.delete(${id}))`;
  if (!source.includes(entry) || !source.includes(timer)) throw new Error(`Pinned ${map} timeout changed.`);
  source = source.replace(entry, `let requestTimer;
      ${map}.set(${id}, {
        resolve: value => { clearTimeout(requestTimer); resolve(value); },
        reject: error => { clearTimeout(requestTimer); reject(error); }${extra}
      });`);
  source = source.replace(timer, `requestTimer = ${timer}`);
}
const configValues = 'function handleValues(msg) {\n    lastValues = msg.values;';
if (!source.includes(configValues)) throw new Error('Pinned config response handler changed.');
source = source.replace(configValues, `function handleValues(msg) {
    if (msg.error) {
      const pending = pendingGets.get(msg.id);
      if (pending) { pendingGets.delete(msg.id); pending.reject(new Error(msg.error)); }
      return;
    }
    lastValues = msg.values;`);
// Authorization failures omit success-only payloads; settle before validating them.
const permissionResponses = [
  ['resolvePending(msg.id, msg.pubkey);', 'resolveOrReject(msg.id, msg.pubkey, msg.error);'],
  ['case "inc.channel.list.result": {\n        if (typeof msg.id !== "string" || !isChannelInfoList(msg.channels)) return;',
    `case "inc.channel.list.result": {
        if (typeof msg.id !== "string") return;
        if (msg.error !== void 0) {
          if (typeof msg.error !== "string" || !msg.error) return;
          const pending = pendingList.get(msg.id);
          if (!pending) return;
          pendingList.delete(msg.id);
          clearTimeout(pending.timeout);
          pending.reject(new Error(msg.error));
          return;
        }
        if (!isChannelInfoList(msg.channels)) return;`],
];
for (const [before, after] of permissionResponses) {
  if (source.split(before).length !== 2) throw new Error('Pinned permission response handler changed.');
  source = source.replace(before, after);
}
writeFileSync(
  new URL('../src/lib/napp/prelude.generated.ts', import.meta.url),
  '// Generated by scripts/generate-napplet-prelude.mjs from @napplet/shim (MIT).\n' +
    '// Copyright (c) 2026 napplet contributors. See THIRD_PARTY_NOTICES.md.\n' +
    `export const nappletPrelude = ${JSON.stringify(source)};\n`,
);
