import { act, create, type ReactTestRenderer } from 'react-test-renderer';
import { ApplicationDetailsActions } from '../ApplicationDetailsActions';
import { HeaderActionMenu } from '@/components/common/HeaderActionMenu';
import { router } from 'expo-router';
import type { ExploreEntry } from '@/services/explore/model';
const mockFavorite = jest.fn();
let mockState = { account: 'account', loaded: true, entries: [] as ExploreEntry[] };
jest.mock('@/stores/explore.store', () => ({ useExplore: () => mockState }));
jest.mock('@/hooks/use-application-favorite', () => ({ useApplicationFavorite: () => mockFavorite }));
jest.mock('@/services/explore/service', () => ({ exploreService: { activate: jest.fn(), forget: jest.fn(async () => {}) } }));
jest.mock('@/hooks/use-clipboard', () => ({ useClipboard: () => ({ copyText: jest.fn(async () => true) }) }));
jest.mock('@/stores/toast.store', () => ({ showToast: jest.fn() }));
jest.mock('expo-router', () => ({ router: { push: jest.fn() } }));
jest.mock('react-i18next', () => ({ useTranslation: () => ({ t: (key: string) => key }) }));
jest.mock('@/components/common/IconButton', () => ({ IconButton: 'IconButton' }));
jest.mock('@/components/common/HeaderActionMenu', () => ({ HeaderActionMenu: 'Menu', HEADER_ACTION_MENU_ICON_SIZE: 20 }));
jest.mock('@/stores/theme.store', () => ({ useThemeStore: (select: (state: object) => unknown) => select({ accent: 'blue' }) }));
jest.mock('lucide-react-native/icons/ellipsis', () => () => null);
jest.mock('lucide-react-native/icons/copy', () => () => null);
jest.mock('lucide-react-native/icons/plus', () => () => null);
jest.mock('lucide-react-native/icons/trash-2', () => () => null);
jest.mock('@solar-icons/react-native/category/security/Linear/ShieldCheck', () => ({ ShieldCheck: () => null }), { virtual: true });
jest.mock('@solar-icons/react-native/category/ui/Linear/Share', () => ({ Share: () => null }), { virtual: true });
const app: ExploreEntry = { key: 'notes', address: 'https://example.com', title: 'Notes', kind: 'website', description: '', required: [], servers: [], desktopPosition: null, lastUsedAt: null };
let renderer: ReactTestRenderer;
const render = () => <ApplicationDetailsActions entry={app} account="account" onShare={() => {}} />;
const items = () => renderer.root.findByType(HeaderActionMenu).props.items as { key: string; title: string; tone?: string; onPress(): void }[];
afterEach(() => { act(() => renderer?.unmount()); jest.clearAllMocks(); });
it('shows Favorite and permissions without Remove for an unused app', async () => {
  mockState.entries = [];
  await act(async () => { renderer = create(render()); });
  expect(items().map(item => item.key)).toEqual(['copy', 'permissions', 'share', 'favorite']);
  expect(items().find(item => item.key === 'favorite')?.title).toBe('napplets.add_app');
  act(() => { items().find(item => item.key === 'favorite')!.onPress(); });
  expect(mockFavorite).toHaveBeenCalledWith(app, true);
  act(() => { items().find(item => item.key === 'permissions')!.onPress(); });
  expect(router.push).toHaveBeenCalledWith({ pathname: '/explore-details', params: { address: app.address, permissions: '1' } });
});
it('reads saved state without exposing history removal in details', async () => {
  const saved = { ...app, desktopPosition: 0, lastUsedAt: 100 };
  mockState.entries = [saved];
  await act(async () => { renderer = create(render()); });
  expect(items().find(item => item.key === 'favorite')).toMatchObject({ title: 'napplets.remove_app', tone: 'danger' });
  expect(items().some(item => item.key === 'remove')).toBe(false);
  act(() => { items().find(item => item.key === 'favorite')!.onPress(); });
  expect(mockFavorite).toHaveBeenCalledWith(saved, false);
});
